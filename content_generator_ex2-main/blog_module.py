from utils import ask_ollama


def generate_blog(topic, style, tone, word_count):

    prompt = f"""
Write a complete blog about "{topic}".

Requirements:
- Writing Style: {style}
- Tone: {tone}
- Approximate Word Count: {word_count} words
- Include an attractive introduction.
- Use meaningful headings and subheadings.
- Explain the topic clearly.
- Include relevant examples.
- End with a conclusion.
- Do not mention that the content was generated by AI.

Generate only the blog.
"""

    print("\nGenerating Blog...")
    print("----------------------------------------")

    blog = ask_ollama(prompt)

    print(blog)

    return blog